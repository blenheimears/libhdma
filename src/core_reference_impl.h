/* Replay dequantization directly from the quantized encoder bands. This avoids
 * the core entropy decoder, but retains bit-exact fixed-point synthesis. */
static int32_t hdma_dequantize(int32_t input,unsigned abits,unsigned scale_index) {
    if (!abits || scale_index >= 128 || abits >= 32) return 0;
    int64_t step_scale = (int64_t)hdma_quant[abits] * hdma_scale[scale_index];
    unsigned shift = 0;
    if (step_scale > (1 << 23)) {
        uint64_t v=(uint64_t)step_scale >> 23;
        while (v) {shift++;v>>=1;}
        step_scale >>= shift;
    }
    return clip23(norm__((int64_t)input*step_scale,22-(int)shift));
}
static int32_t hdma_lfe_dequantize(int8_t input,unsigned scale_index) {
    if (scale_index >= 128) return 0;
    /* FFmpeg: scale = mul23(4697620, scale_table[index]);
     * sample = clip23(audio * scale >> 4). */
    int32_t scale=mul23(4697620,(int32_t)hdma_scale[scale_index]);
    return clip23((int64_t)input * scale >> 4);
}
